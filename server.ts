interface AuthPayload {
  role: 'student' | 'admin';
  studentId?: string;
  nis?: string;
  username?: string;
  exp: number;
}

const TOKEN_SECRET =
  process.env.SESSION_SECRET || 'smpn2ciamis_pjok_secret_2026_galih';

function signToken(payload: Omit<AuthPayload, 'exp'>): string {
  const full: AuthPayload = {
    ...payload,
    exp: Date.now() + 1000 * 60 * 60 * 24 * 7,
  };
  const body = Buffer.from(JSON.stringify(full)).toString('base64url');
  const sig = crypto
    .createHmac('sha256', TOKEN_SECRET)
    .update(body)
    .digest('base64url');
  return `${body}.${sig}`;
}

function verifyToken(token: string | undefined): AuthPayload | null {
  if (!token) return null;
  const parts = token.split('.');
  if (parts.length !== 2) return null;
  const [body, sig] = parts;
  const expected = crypto
    .createHmac('sha256', TOKEN_SECRET)
    .update(body)
    .digest('base64url');
  if (sig !== expected) return null;
  try {
    const parsed = JSON.parse(
      Buffer.from(body, 'base64url').toString('utf-8')
    ) as AuthPayload;
    if (parsed.exp < Date.now()) return null;
    return parsed;
  } catch {
    return null;
  }
}

function extractBearer(req: Request): string | undefined {
  const header = req.headers.authorization;
  if (header && header.startsWith('Bearer ')) {
    return header.slice(7).trim();
  }
  return undefined;
}

function requireAuth(role: 'student' | 'admin') {
  return (req: Request, res: Response, next: NextFunction) => {
    const payload = verifyToken(extractBearer(req));
    if (!payload || payload.role !== role) {
      res.status(401).json({ error: 'Sesi tidak valid atau telah berakhir.' });
      return;
    }
    (req as Request & { auth?: AuthPayload }).auth = payload;
    next();
  };
}

