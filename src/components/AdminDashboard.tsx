  async function handleWebNfcTap() {
    const Win = window as unknown as {
      NDEFReader?: new () => {
        scan: () => Promise<void>;
        onreading:
          | ((ev: {
              serialNumber?: string;
              message?: {
                records?: Array<{ recordType?: string; data?: DataView }>;
              };
            }) => void)
          | null;
        onreadingerror: (() => void) | null;
      };
    };
    if (!Win.NDEFReader) {
      setUsbModeActive(true);
      rfidInputRef.current?.focus();
      setFeedbackBanner({
        type: 'error',
        text: 'Web NFC bawaan HP hanya aktif di Chrome Android HTTPS luar iframe. Untuk perangkat ini, gunakan USB RFID/NFC Reader pada kolom di atas (otomatis terbaca).',
      });
      return;
    }
    try {
      const ndef = new Win.NDEFReader();
      await ndef.scan();
      setNfcListening(true);
      setFeedbackBanner({
        type: 'success',
        text: 'Sensor Web NFC aktif! Tempelkan kartu NFC ke bagian belakang perangkat Anda.',
      });
      ndef.onreading = (ev) => {
        let detectedCode = ev.serialNumber || '';
        const textRecord = ev.message?.records?.find(
          (r) => r.recordType === 'text' && r.data
        );
        if (textRecord?.data) {
          const decoded = new TextDecoder().decode(textRecord.data).trim();
          if (decoded) detectedCode = decoded;
        }
        if (detectedCode) {
          void scanCallbackRef.current(detectedCode, 'NFC_TAP');
        }
      };
      ndef.onreadingerror = () => {
        setFeedbackBanner({
          type: 'error',
          text: 'Kartu NFC terbaca tidak sempurna. Tempelkan ulang kartu ke sensor.',
        });
      };
    } catch {
      setNfcListening(false);
      setUsbModeActive(true);
      rfidInputRef.current?.focus();
      setFeedbackBanner({
        type: 'error',
        text: 'Izin sensor Web NFC diblokir browser/iframe. Mode USB RFID/NFC Reader tetap aktif dan siap digunakan.',
      });
    }
  }

