function compressImageToDataUrl(file: File, maxDim = 400): Promise<string> {
  return new Promise((resolve, reject) => {
    const reader = new FileReader();
    reader.onload = () => {
      const img = new Image();
      img.onload = () => {
        const canvas = document.createElement('canvas');
        const ctx = canvas.getContext('2d');
        if (!ctx) {
          resolve(String(reader.result));
          return;
        }
        const scaleFactors = [1, 0.78, 0.6];
        const qualities = [0.85, 0.7, 0.55, 0.42];
        let best = '';

        for (const sf of scaleFactors) {
          const dim = Math.max(120, Math.round(maxDim * sf));
          const scale = Math.min(1, dim / Math.max(img.width, img.height));
          canvas.width = Math.max(1, Math.round(img.width * scale));
          canvas.height = Math.max(1, Math.round(img.height * scale));
          ctx.clearRect(0, 0, canvas.width, canvas.height);
          ctx.drawImage(img, 0, 0, canvas.width, canvas.height);

          for (const q of qualities) {
            best = canvas.toDataURL('image/jpeg', q);
            if (best.length <= MAX_CLOUD_MEDIA_CHARS) {
              resolve(best);
              return;
            }
          }
        }
        resolve(best);
      };
      img.onerror = () => reject(new Error('Gagal membaca gambar'));
      img.src = String(reader.result);
    };
    reader.onerror = () => reject(new Error('Gagal membaca file'));
    reader.readAsDataURL(file);
  });
}

