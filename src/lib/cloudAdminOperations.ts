export function applyImportStudentsCloudLocal(
  payload: AdminDashboardPayload,
  rows: Array<{
    nis?: string;
    name?: string;
    className?: string;
    gender?: 'L' | 'P';
    rfidUid?: string;
    qrCodeValue?: string;
    parentName?: string;
    parentWhatsapp?: string;
    primarySportInterest?: string;
    nonAcademicActivity?: string;
  }>,
  mode: 'merge' | 'replace'
):
  | {
      ok: true;
      nextPayload: AdminDashboardPayload;
      mode: 'merge' | 'replace';
      createdCount: number;
      updatedCount: number;
      removedCount: number;
    }
  | { ok: false; error: string } {
  const validRows = rows.filter(
    (r) =>
      String(r.nis ?? '').trim().length > 0 &&
      String(r.name ?? '').trim().length > 0
  );
  if (validRows.length === 0) {
    return {
      ok: false,
      error:
        'Tidak ada data siswa yang valid pada file (wajib memiliki kolom NISN dan Nama_Siswa).',
    };
  }

  const importMode = mode === 'replace' ? 'replace' : 'merge';
  let createdCount = 0;
  let updatedCount = 0;
  let removedCount = 0;
  const batchTs = Date.now();
  let nextRawStudents: StudentRecord[];
  let nextGrades = payload.grades;
  let nextAttendance = payload.attendance;
  let nextNotifications = payload.notifications;

  if (importMode === 'replace') {
    const previousByNis = new Map(payload.students.map((s) => [s.nis, s]));
    const replacedByNis = new Map<string, StudentRecord>();

    validRows.forEach((row, idx) => {
      const nis = String(row.nis ?? '').trim();
      const name = String(row.name ?? '').trim();
      if (!nis || !name) return;

      const prev = previousByNis.get(nis);
      if (prev) {
        replacedByNis.set(nis, {
          ...prev,
          nis,
          name,
          className: row.className?.trim() || prev.className,
          gender:
            row.gender === 'L' || row.gender === 'P' ? row.gender : prev.gender,
          rfidUid: row.rfidUid?.trim() || prev.rfidUid,
          qrCodeValue: row.qrCodeValue?.trim() || prev.qrCodeValue,
          parentName: row.parentName?.trim() || prev.parentName,
          parentWhatsapp: row.parentWhatsapp
            ? normalizePhone(row.parentWhatsapp)
            : prev.parentWhatsapp,
          primarySportInterest:
            row.primarySportInterest?.trim() || prev.primarySportInterest,
          nonAcademicActivity:
            row.nonAcademicActivity?.trim() || prev.nonAcademicActivity,
        });
        updatedCount += 1;
      } else {
        replacedByNis.set(nis, {
          id: `stu-imp-${batchTs}-${idx}`,
          nis,
          name,
          className: String(row.className || 'VII A').trim(),
          gender: row.gender === 'P' ? 'P' : 'L',
          rfidUid: row.rfidUid?.trim() || `RF-${nis.slice(-6)}`,
          qrCodeValue: row.qrCodeValue?.trim() || `SMPN2PJOK:${nis}`,
          qrImageUrl: '',
          parentName: row.parentName?.trim() || `Wali ${name}`,
          parentWhatsapp: normalizePhone(row.parentWhatsapp || '6281200000000'),
          photoUrl: '',
          primarySportInterest: row.primarySportInterest?.trim() || 'Atletik',
          nonAcademicActivity:
            row.nonAcademicActivity?.trim() || 'Pramuka Inti',
        });
        createdCount += 1;
      }
    });

    nextRawStudents = Array.from(replacedByNis.values());
    const keptIds = new Set(nextRawStudents.map((s) => s.id));
    removedCount = payload.students.filter((s) => !keptIds.has(s.id)).length;
    nextGrades = payload.grades.filter((g) => keptIds.has(g.studentId));
    nextAttendance = payload.attendance.filter((a) => keptIds.has(a.studentId));
    nextNotifications = payload.notifications.filter((n) =>
      keptIds.has(n.studentId)
    );
  } else {
    nextRawStudents = payload.students.map((s) => ({ ...s }));
    validRows.forEach((row, idx) => {
      const nis = String(row.nis ?? '').trim();
      const name = String(row.name ?? '').trim();
      if (!nis || !name) return;
      const existing = nextRawStudents.find((s) => s.nis === nis);
      if (existing) {
        existing.name = name;
        if (row.className) existing.className = row.className.trim();
        if (row.gender === 'L' || row.gender === 'P') {
          existing.gender = row.gender;
        }
        if (row.rfidUid) existing.rfidUid = row.rfidUid.trim();
        if (row.qrCodeValue) existing.qrCodeValue = row.qrCodeValue.trim();
        if (row.parentName) existing.parentName = row.parentName.trim();
        if (row.parentWhatsapp) {
          existing.parentWhatsapp = normalizePhone(row.parentWhatsapp);
        }
        if (row.primarySportInterest) {
          existing.primarySportInterest = row.primarySportInterest.trim();
        }
        if (row.nonAcademicActivity) {
          existing.nonAcademicActivity = row.nonAcademicActivity.trim();
        }
        updatedCount += 1;
      } else {
        nextRawStudents.push({
          id: `stu-imp-${batchTs}-${idx}`,
          nis,
          name,
          className: String(row.className || 'VII A').trim(),
          gender: row.gender === 'P' ? 'P' : 'L',
          rfidUid: row.rfidUid?.trim() || `RF-${nis.slice(-6)}`,
          qrCodeValue: row.qrCodeValue?.trim() || `SMPN2PJOK:${nis}`,
          qrImageUrl: '',
          parentName: row.parentName?.trim() || `Wali ${name}`,
          parentWhatsapp: normalizePhone(row.parentWhatsapp || '6281200000000'),
          photoUrl: '',
          primarySportInterest: row.primarySportInterest?.trim() || 'Atletik',
          nonAcademicActivity:
            row.nonAcademicActivity?.trim() || 'Pramuka Inti',
        });
        createdCount += 1;
      }
    });
  }

  const nextStudents = recomputeStudentSummaries(
    nextRawStudents,
    nextGrades,
    nextAttendance,
    payload.settings.activeSemester,
    payload.availableMaterials
  );

  return {
    ok: true,
    mode: importMode,
    createdCount,
    updatedCount,
    removedCount,
    nextPayload: {
      ...payload,
      students: nextStudents,
      grades: nextGrades,
      attendance: nextAttendance,
      notifications: nextNotifications,
      availableClasses: extractActiveClasses(nextStudents),
    },
  };
}

