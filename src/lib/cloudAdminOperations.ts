export function applySaveSemesterCloudLocal(
  payload: AdminDashboardPayload,
  params: {
    originalName?: string;
    name?: string;
    kkm?: number;
    setActive?: boolean;
  }
):
  | {
      ok: true;
      nextPayload: AdminDashboardPayload;
      semesters: string[];
      semesterKkm: Record<string, number>;
      activeSemester: string;
    }
  | { ok: false; error: string } {
  const trimmedName = String(params.name ?? '').trim();
  if (!trimmedName) {
    return { ok: false, error: 'Nama Periode / Semester wajib diisi.' };
  }
  const parsedKkm =
    params.kkm !== undefined &&
    params.kkm !== null &&
    !Number.isNaN(Number(params.kkm))
      ? Math.max(0, Math.min(100, Math.round(Number(params.kkm))))
      : undefined;

  const semesters = [...payload.availableSemesters];
  const kkmMap: Record<string, number> = { ...payload.semesterKkm };
  let nextGrades = payload.grades;
  let nextActiveSemester = payload.settings.activeSemester;

  if (params.originalName) {
    const idx = semesters.findIndex((s) => s === params.originalName);
    if (idx === -1) {
      return { ok: false, error: 'Semester yang akan diedit tidak ditemukan.' };
    }
    if (
      trimmedName !== params.originalName &&
      semesters.some((s) => s.toLowerCase() === trimmedName.toLowerCase())
    ) {
      return { ok: false, error: `Periode "${trimmedName}" sudah terdaftar.` };
    }
    semesters[idx] = trimmedName;
    const prevKkm = kkmMap[params.originalName] ?? DEFAULT_KKM;
    if (trimmedName !== params.originalName) {
      delete kkmMap[params.originalName];
    }
    kkmMap[trimmedName] = parsedKkm ?? prevKkm;
    nextGrades = payload.grades.map((g) =>
      g.semester === params.originalName ? { ...g, semester: trimmedName } : g
    );
    if (nextActiveSemester === params.originalName) {
      nextActiveSemester = trimmedName;
    }
  } else {
    const existingMatch = semesters.find(
      (s) => s.toLowerCase() === trimmedName.toLowerCase()
    );
    if (existingMatch && !params.setActive && parsedKkm === undefined) {
      return {
        ok: false,
        error: `Periode "${trimmedName}" sudah ada dalam daftar.`,
      };
    }
    if (!existingMatch) {
      semesters.push(trimmedName);
    }
    const targetKey = existingMatch || trimmedName;
    if (parsedKkm !== undefined) {
      kkmMap[targetKey] = parsedKkm;
    } else if (typeof kkmMap[targetKey] !== 'number') {
      kkmMap[targetKey] = DEFAULT_KKM;
    }
  }

  if (params.setActive) {
    nextActiveSemester = trimmedName;
  }

  const nextSettings = {
    ...payload.settings,
    activeSemester: nextActiveSemester,
  };
  const nextStudents = recomputeStudentSummaries(
    payload.students,
    nextGrades,
    payload.attendance,
    nextActiveSemester,
    payload.availableMaterials
  );

  return {
    ok: true,
    semesters,
    semesterKkm: kkmMap,
    activeSemester: nextActiveSemester,
    nextPayload: {
      ...payload,
      settings: nextSettings,
      availableSemesters: semesters,
      semesterKkm: kkmMap,
      grades: nextGrades,
      students: nextStudents,
    },
  };
}

export function applyDeleteSemesterCloudLocal(
  payload: AdminDashboardPayload,
  name: string
):
  | {
      ok: true;
      nextPayload: AdminDashboardPayload;
      activeSemester: string;
    }
  | { ok: false; error: string } {
  const targetName = String(name ?? '').trim();
  if (!targetName) {
    return { ok: false, error: 'Nama semester wajib diisi.' };
  }
  if (payload.availableSemesters.length <= 1) {
    return { ok: false, error: 'Minimal harus tersedia 1 Periode / Semester.' };
  }
  const filtered = payload.availableSemesters.filter((s) => s !== targetName);
  if (filtered.length === payload.availableSemesters.length) {
    return { ok: false, error: 'Semester tidak ditemukan.' };
  }
  const kkmMap = { ...payload.semesterKkm };
  delete kkmMap[targetName];
  const nextActive =
    payload.settings.activeSemester === targetName
      ? filtered[0]
      : payload.settings.activeSemester;

  return {
    ok: true,
    activeSemester: nextActive,
    nextPayload: {
      ...payload,
      availableSemesters: filtered,
      semesterKkm: kkmMap,
      settings: {
        ...payload.settings,
        activeSemester: nextActive,
      },
    },
  };
}

