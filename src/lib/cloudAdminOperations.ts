export type ApiFetchResult<T> =
  | { reachable: false }
  | { reachable: true; ok: boolean; status: number; data: T };

/**
 * Safely calls a backend `/api/*` endpoint.
 * Returns `{ reachable: false }` instead of throwing SyntaxError when the hosting
 * environment is static-only / returns HTML (`index.html`), 404/405/5xx gateway HTML,
 * or cannot reach the Express server.
 */
export async function tryJsonApiFetch<T = Record<string, unknown>>(
  input: string,
  init?: RequestInit,
  skipServer = false
): Promise<ApiFetchResult<T>> {
  if (skipServer) {
    return { reachable: false };
  }
  try {
    const res = await fetch(input, init);
    const contentType = (res.headers.get('content-type') || '').toLowerCase();
    if (!contentType.includes('application/json')) {
      return { reachable: false };
    }
    const data = (await res.json()) as T;
    return {
      reachable: true,
      ok: res.ok,
      status: res.status,
      data,
    };
  } catch {
    return { reachable: false };
  }
}

export async function tryJsonApiFetchWithRetry<T = Record<string, unknown>>(
  input: string,
  init?: RequestInit,
  skipServer = false,
  retries = 2
): Promise<ApiFetchResult<T>> {
  if (skipServer) {
    return { reachable: false };
  }
  for (let attempt = 0; attempt <= retries; attempt++) {
    try {
      const res = await fetch(input, init);
      const contentType = (res.headers.get('content-type') || '').toLowerCase();
      if (!contentType.includes('application/json')) {
        return { reachable: false };
      }
      const data = (await res.json()) as T;
      return {
        reachable: true,
        ok: res.ok,
        status: res.status,
        data,
      };
    } catch {
      if (attempt < retries) {
        await new Promise((resolve) =>
          setTimeout(resolve, attempt === 0 ? 350 : 800)
        );
      }
    }
  }
  return { reachable: false };
}

export function normalizePhone(raw: string): string {
  const digits = raw.replace(/\D/g, '');
  if (!digits) return '';
  if (digits.startsWith('0')) return `62${digits.slice(1)}`;
  if (digits.startsWith('62')) return digits;
  return `62${digits}`;
}

export function buildWhatsappUrl(phone: string, text: string): string {
  const clean = normalizePhone(phone);
  return `https://wa.me/${clean}?text=${encodeURIComponent(text)}`;
}

function parseOptionalScore(
  raw: number | string | null | undefined
): number | null {
  if (raw === undefined || raw === null) return null;
  const str = String(raw).trim();
  if (str === '' || str === '-' || str.toLowerCase() === 'kosong') return null;
  const num = Number(str.replace(',', '.'));
  if (Number.isNaN(num)) return null;
  return Math.max(0, Math.min(100, Math.round(num)));
}

export function recomputeStudentSummaries(
  students: StudentRecord[],
  grades: GradeRecord[],
  attendance: AttendanceRecord[],
  activeSemester: string,
  availableMaterials: { code: MaterialCode; name: string }[]
): AdminStudentSummary[] {
  return students.map((stu) => {
    const sGrades = grades.filter((g) => g.studentId === stu.id);
    const sAtt = attendance.filter((a) => a.studentId === stu.id);
    const latestAttendance = [...sAtt].sort((a, b) =>
      `${b.date} ${b.time}`.localeCompare(`${a.date} ${a.time}`)
    )[0];
    const futStats = computeFutStats(
      stu,
      sGrades,
      sAtt,
      activeSemester,
      availableMaterials
    );
    const talent = analyzeTalent(stu, sGrades, sAtt, futStats);
    return {
      ...stu,
      futStats,
      talent,
      latestAttendance,
      gradesCount: sGrades.length,
    };
  });
}

export function applySingleGradeCloudLocal(
  payload: AdminDashboardPayload,
  input: {
    studentId: string;
    semester: string;
    materialCode: MaterialCode;
    praktikScore: number | string | null;
    pengetahuanScore: number | string | null;
    teacherNote?: string;
    remedialDetail?: string;
  }
):
  | {
      ok: true;
      savedGrades: GradeRecord[];
      notification: NotificationRecord;
    }
  | { ok: false; error: string } {
  const { studentId, semester, materialCode } = input;
  if (!studentId || !semester || !materialCode) {
    return { ok: false, error: 'Siswa, semester, dan materi wajib dipilih.' };
  }

  const pScore = parseOptionalScore(input.praktikScore);
  const kScore = parseOptionalScore(input.pengetahuanScore);
  const trimmedNote = String(input.teacherNote ?? '').trim();
  const trimmedDetail = String(input.remedialDetail ?? '').trim();

  if (pScore === null && kScore === null && !trimmedNote && !trimmedDetail) {
    return {
      ok: false,
      error:
        'Isi minimal salah satu nilai (Praktik/Pengetahuan) atau detail keterangan guru.',
    };
  }

  const student = payload.students.find((s) => s.id === studentId);
  if (!student) {
    return { ok: false, error: 'Siswa tidak ditemukan.' };
  }

  const availableMaterials = payload.availableMaterials;
  const matInfo = availableMaterials.find((m) => m.code === materialCode) ?? {
    code: materialCode,
    name: materialCode,
  };

  const nowIso = new Date().toISOString();
  const autoDesc = buildAutoGradeDescription(pScore, kScore, matInfo.name);
  const defaultNote =
    autoDesc ||
    'Silakan minta nilai dengan praktik atau tugas kepada guru PJOK.';

  const existing = payload.grades.find(
    (g) =>
      g.studentId === studentId &&
      g.semester === semester &&
      g.materialCode === materialCode
  );

  const prevKScore = existing?.pengetahuanScore ?? null;
  const savedGrade: GradeRecord = existing
    ? {
        ...existing,
        materialName: matInfo.name,
        praktikScore: pScore,
        pengetahuanScore: kScore,
        teacherNote:
          trimmedNote ||
          (autoDesc && isReplaceableAutoOrPlaceholderNote(existing.teacherNote)
            ? autoDesc
            : pScore === null || kScore === null
              ? defaultNote
              : existing.teacherNote),
        remedialDetail: trimmedDetail || undefined,
        updatedAt: nowIso,
      }
    : {
        id: `grd-${Date.now()}-${Math.random().toString(36).slice(2, 6)}`,
        studentId,
        semester,
        materialCode,
        materialName: matInfo.name,
        praktikScore: pScore,
        pengetahuanScore: kScore,
        teacherNote: trimmedNote || defaultNote,
        remedialDetail: trimmedDetail || undefined,
        updatedAt: nowIso,
      };

  const syncedGrades: GradeRecord[] = [savedGrade];
  const shouldSyncPengetahuan = kScore !== null || prevKScore !== null;
  if (shouldSyncPengetahuan) {
    payload.grades.forEach((other) => {
      if (
        other.studentId !== studentId ||
        other.semester !== semester ||
        other.materialCode === matInfo.code
      ) {
        return;
      }
      const matMeta = availableMaterials.find(
        (m) => m.code === other.materialCode
      );
      const matName = matMeta?.name || other.materialName || other.materialCode;
      const scoreChanged = other.pengetahuanScore !== kScore;
      const otherAuto = buildAutoGradeDescription(
        other.praktikScore,
        kScore,
        matName
      );
      const noteNeedsRefresh = isReplaceableAutoOrPlaceholderNote(
        other.teacherNote
      );
      if (
        scoreChanged ||
        (noteNeedsRefresh && otherAuto && other.teacherNote !== otherAuto)
      ) {
        syncedGrades.push({
          ...other,
          materialName: matName,
          pengetahuanScore: kScore,
          teacherNote: noteNeedsRefresh
            ? otherAuto ||
              'Silakan minta nilai dengan praktik atau tugas kepada guru PJOK.'
            : other.teacherNote,
          updatedAt: nowIso,
        });
      }
    });
  }

  const activeKkm = resolveEffectiveKkm({
    className: student.className,
    semester,
    semesterKkm: payload.semesterKkm,
    classKkm: payload.classKkm,
    fallbackKkm: DEFAULT_KKM,
  });
  const pText = pScore !== null ? String(pScore) : 'Kosong';
  const kText = kScore !== null ? String(kScore) : 'Kosong';
  const avgMateri =
    pScore !== null && kScore !== null
      ? Math.round((pScore + kScore) / 2)
      : pScore ?? kScore;
  const isBelowKkm =
    (pScore !== null && pScore < activeKkm) ||
    (kScore !== null && kScore < activeKkm) ||
    (avgMateri !== null && avgMateri < activeKkm);
  const hasEmpty = pScore === null || kScore === null;

  const extraInfo = trimmedDetail || trimmedNote;
  const waMessage = hasEmpty
    ? `[SMPN 2 Ciamis - Info Tugas & Nilai PJOK] Yth. ${student.parentName}, materi "${matInfo.name}" (${semester}) ananda ${student.name} (${student.className}) masih terdapat nilai kosong (Praktik: ${pText}, Pengetahuan: ${kText}). Silakan minta nilai dengan praktik atau tugas kepada ${payload.settings.teacherName}.${extraInfo ? ` Keterangan: ${extraInfo}` : ''}`
    : isBelowKkm
      ? `[SMPN 2 Ciamis - Perbaikan Nilai PJOK] Yth. ${student.parentName}, nilai materi "${matInfo.name}" (${semester}) ananda ${student.name} (${student.className}) berada di bawah KKM ${activeKkm}: Praktik ${pText}, Pengetahuan ${kText} (Rata-rata ${avgMateri}). Mohon dukungan untuk perbaikan praktik/tugas.${extraInfo ? ` Catatan Guru: ${extraInfo}` : ''}`
      : `[SMPN 2 Ciamis - Progres Nilai PJOK] Yth. ${student.parentName}, nilai materi "${matInfo.name}" (${semester}) ananda ${student.name} (${student.className}) telah diperbarui oleh ${payload.settings.teacherName}: Nilai Praktik ${pText}, Nilai Pengetahuan ${kText} (Rata-rata ${avgMateri}). Pantau detail lewat Portal PJOK dengan NISN ${student.nis}.`;

  const notif: NotificationRecord = {
    id: `notif-${Date.now()}-${Math.random().toString(36).slice(2, 6)}`,
    studentId: student.id,
    targetRole: 'all',
    type: 'GRADE_UPDATE',
    title: hasEmpty
      ? `Keterangan Nilai Kosong: ${matInfo.name}`
      : isBelowKkm
        ? `Perlu Perbaikan (< KKM ${activeKkm}): ${matInfo.name}`
        : `Pembaruan Nilai ${matInfo.name}`,
    message: `${payload.settings.teacherName} (${semester}): Praktik ${pText} · Pengetahuan ${kText}.${extraInfo ? ` ${extraInfo}` : ''}`,
    isRead: false,
    whatsappSent: false,
    whatsappUrl: buildWhatsappUrl(student.parentWhatsapp, waMessage),
    createdAt: nowIso,
  };

  return { ok: true, savedGrades: syncedGrades, notification: notif };
}

export function applyBatchGradesCloudLocal(
  payload: AdminDashboardPayload,
  items: Array<{
    studentId: string;
    semester: string;
    materialCode: string;
    praktikScore: number | string | null;
    pengetahuanScore: number | string | null;
    teacherNote?: string;
    remedialDetail?: string;
  }>
):
  | {
      ok: true;
      savedGrades: GradeRecord[];
      createdNotifications: NotificationRecord[];
      updatedCount: number;
    }
  | { ok: false; error: string } {
  const validItems = items.filter(
    (it) => it.studentId && it.semester && it.materialCode
  );
  if (validItems.length === 0) {
    return { ok: false, error: 'Tidak ada perubahan nilai yang dikirim.' };
  }

  const workingGrades = payload.grades.map((g) => ({ ...g }));
  const availableMaterials = payload.availableMaterials;
  const nowIso = new Date().toISOString();
  const batchTs = Date.now();
  const savedGrades: GradeRecord[] = [];
  const createdNotifications: NotificationRecord[] = [];
  const pengetahuanSyncTargets = new Map<
    string,
    { studentId: string; semester: string; score: number | null }
  >();

  validItems.forEach((item, idx) => {
    const student = payload.students.find((s) => s.id === item.studentId);
    if (!student) return;
    const semester = String(
      item.semester || payload.settings.activeSemester
    ).trim();
    const matCode = String(item.materialCode || '').trim();
    const matInfo = availableMaterials.find((m) => m.code === matCode) ?? {
      code: matCode,
      name: matCode,
    };
    const pScore = parseOptionalScore(item.praktikScore);
    const kScore = parseOptionalScore(item.pengetahuanScore);
    const trimmedNote = String(item.teacherNote ?? '').trim();
    const trimmedDetail = String(item.remedialDetail ?? '').trim();
    if (
      pScore === null &&
      kScore === null &&
      !trimmedNote &&
      !trimmedDetail
    ) {
      return;
    }

    const autoDesc = buildAutoGradeDescription(pScore, kScore, matInfo.name);
    const isCustomNote =
      trimmedNote.length > 0 && !isAutoGeneratedGradeDescription(trimmedNote);
    const defaultNote =
      autoDesc ||
      'Silakan minta nilai dengan praktik atau tugas kepada guru PJOK.';

    const existing = workingGrades.find(
      (g) =>
        g.studentId === student.id &&
        g.semester === semester &&
        g.materialCode === matInfo.code
    );
    const prevKScore = existing?.pengetahuanScore ?? null;
    if (kScore !== prevKScore) {
      pengetahuanSyncTargets.set(`${student.id}::${semester}`, {
        studentId: student.id,
        semester,
        score: kScore,
      });
    }

    let savedGrade: GradeRecord;
    if (existing) {
      existing.materialName = matInfo.name;
      existing.praktikScore = pScore;
      existing.pengetahuanScore = kScore;
      existing.teacherNote = isCustomNote
        ? trimmedNote
        : autoDesc &&
            (isReplaceableAutoOrPlaceholderNote(existing.teacherNote) ||
              isAutoGeneratedGradeDescription(trimmedNote) ||
              !trimmedNote)
          ? autoDesc
          : pScore === null || kScore === null
            ? defaultNote
            : existing.teacherNote;
      if (trimmedDetail) {
        existing.remedialDetail = trimmedDetail;
      }
      existing.updatedAt = nowIso;
      savedGrade = existing;
    } else {
      savedGrade = {
        id: `grd-${batchTs}-${idx}-${Math.random().toString(36).slice(2, 5)}`,
        studentId: student.id,
        semester,
        materialCode: matInfo.code as MaterialCode,
        materialName: matInfo.name,
        praktikScore: pScore,
        pengetahuanScore: kScore,
        teacherNote: isCustomNote ? trimmedNote : defaultNote,
        remedialDetail: trimmedDetail || undefined,
        updatedAt: nowIso,
      };
      workingGrades.push(savedGrade);
    }
    savedGrades.push(savedGrade);

    const pText = pScore !== null ? String(pScore) : 'Kosong';
    const kText = kScore !== null ? String(kScore) : 'Kosong';
    createdNotifications.push({
      id: `notif-${batchTs}-${idx}-${Math.random().toString(36).slice(2, 5)}`,
      studentId: student.id,
      targetRole: 'all',
      type: 'GRADE_UPDATE',
      title: `Pembaruan Nilai ${matInfo.name}`,
      message: `${payload.settings.teacherName} (${semester}): Praktik ${pText} · Pengetahuan ${kText}.`,
      isRead: false,
      whatsappSent: false,
      whatsappUrl: buildWhatsappUrl(
        student.parentWhatsapp,
        `[SMPN 2 Ciamis - PJOK] Nilai ${matInfo.name} (${semester}) ananda ${student.name} diperbarui: Praktik ${pText}, Pengetahuan ${kText}.`
      ),
      createdAt: nowIso,
    });
  });

  const savedIds = new Set(savedGrades.map((g) => g.id));
  pengetahuanSyncTargets.forEach(({ studentId, semester, score: targetK }) => {
    workingGrades.forEach((other) => {
      if (other.studentId !== studentId || other.semester !== semester) return;
      const matMeta = availableMaterials.find(
        (m) => m.code === other.materialCode
      );
      const matName = matMeta?.name || other.materialName || other.materialCode;
      const scoreChanged = other.pengetahuanScore !== targetK;
      const otherAuto = buildAutoGradeDescription(
        other.praktikScore,
        targetK,
        matName
      );
      const noteNeedsRefresh = isReplaceableAutoOrPlaceholderNote(
        other.teacherNote
      );
      if (
        scoreChanged ||
        (noteNeedsRefresh && otherAuto && other.teacherNote !== otherAuto)
      ) {
        other.materialName = matName;
        other.pengetahuanScore = targetK;
        if (noteNeedsRefresh) {
          other.teacherNote =
            otherAuto ||
            'Silakan minta nilai dengan praktik atau tugas kepada guru PJOK.';
        }
        other.updatedAt = nowIso;
        if (!savedIds.has(other.id)) {
          savedGrades.push(other);
          savedIds.add(other.id);
        }
      }
    });
  });

  return {
    ok: true,
    savedGrades,
    createdNotifications,
    updatedCount: savedGrades.length,
  };
}

export function applyImportGradesCloudLocal(
  payload: AdminDashboardPayload,
  rows: Array<{
    nis?: string;
    name?: string;
    className?: string;
    semester?: string;
    materialCode?: string;
    praktikScore?: number | null;
    pengetahuanScore?: number | null;
    teacherNote?: string;
  }>,
  mode: 'merge' | 'replace'
):
  | {
      ok: true;
      mode: 'merge' | 'replace';
      createdCount: number;
      updatedCount: number;
      editedCount: number;
      removedCount: number;
      createdStudents: number;
      savedGrades: GradeRecord[];
      createdStudentsList: AdminStudentSummary[];
      createdNotifications: NotificationRecord[];
      availableSemesters: string[];
    }
  | { ok: false; error: string } {
  const validRows = rows.filter(
    (r) =>
      String(r.nis ?? '').trim().length > 0 ||
      String(r.name ?? '').trim().length > 0
  );
  if (validRows.length === 0) {
    return {
      ok: false,
      error:
        'Tidak ada baris data nilai yang valid (wajib memiliki kolom NISN atau Nama Siswa).',
    };
  }

  const importMode = mode === 'replace' ? 'replace' : 'merge';
  const availableMaterials = payload.availableMaterials;
  const semesters = [...payload.availableSemesters];
  const studentsList = payload.students.map((s) => ({ ...s }));
  const previousCount = payload.grades.length;
  let workingGrades: GradeRecord[] =
    importMode === 'replace' ? [] : payload.grades.map((g) => ({ ...g }));

  const normalizeTextKey = (val: string) =>
    val.toLowerCase().replace(/[^a-z0-9]/g, '').trim();

  const matchMaterialForImport = (rawInput: string) => {
    const trimmed = String(rawInput || '').trim();
    const upper = trimmed.toUpperCase();
    const aliasCode = resolveMaterialCodeAlias(upper);
    const normInput = normalizeTextKey(trimmed);

    const exact = availableMaterials.find(
      (m) =>
        m.code === upper ||
        m.code === aliasCode ||
        m.name.toLowerCase() === trimmed.toLowerCase() ||
        normalizeTextKey(m.code) === normInput ||
        normalizeTextKey(m.name) === normInput
    );
    if (exact) return exact;

    if (
      normInput.includes('aquatik') ||
      normInput.includes('akuatik') ||
      normInput.includes('renang')
    ) {
      const aq = availableMaterials.find((m) =>
        normalizeTextKey(m.code + m.name).match(/aquatik|akuatik|renang/)
      );
      if (aq) return aq;
    }

    const partial = availableMaterials.find((m) => {
      const mNorm = normalizeTextKey(m.name);
      return (
        normInput.length >= 4 &&
        (mNorm.includes(normInput) || normInput.includes(mNorm))
      );
    });
    return partial ?? availableMaterials[0];
  };

  let editedCount = 0;
  let createdCount = 0;
  let createdStudentsCount = 0;
  const nowIso = new Date().toISOString();
  const batchTs = Date.now();
  const savedGrades: GradeRecord[] = [];
  const createdStudentsRaw: StudentRecord[] = [];
  const createdNotifications: NotificationRecord[] = [];

  validRows.forEach((row, idx) => {
    const rawNis = String(row.nis ?? '').trim().replace(/\.0+$/, '');
    const rawName = String(row.name ?? '').trim();
    const rawClass = String(row.className ?? '').trim();
    if (!rawNis && !rawName) return;

    let student: StudentRecord | undefined = rawNis
      ? studentsList.find((s) => s.nis.trim() === rawNis)
      : undefined;

    if (!student && rawName) {
      const normName = normalizeTextKey(rawName);
      const normClass = normalizeTextKey(rawClass);
      const nameMatches = studentsList.filter(
        (s) => normalizeTextKey(s.name) === normName
      );
      if (normClass) {
        student =
          nameMatches.find((s) => normalizeTextKey(s.className) === normClass) ??
          (nameMatches.length === 1 ? nameMatches[0] : undefined);
      } else if (nameMatches.length === 1) {
        student = nameMatches[0];
      }
    }

    if (!student && rawNis && rawName) {
      const newStu: StudentRecord = {
        id: `stu-${batchTs}-${idx}`,
        nis: rawNis,
        name: rawName,
        className: rawClass || 'VII A',
        gender: 'L',
        rfidUid: `RF-${rawNis.slice(-6)}`,
        parentName: `Orang Tua ${rawName}`,
        parentWhatsapp: '6281200000000',
        photoUrl: '',
        primarySportInterest: 'Atletik',
        nonAcademicActivity: 'Pramuka Inti',
      };
      studentsList.push({
        ...newStu,
        futStats: computeFutStats(
          newStu,
          [],
          [],
          payload.settings.activeSemester,
          availableMaterials
        ),
        talent: analyzeTalent(
          newStu,
          [],
          [],
          computeFutStats(
            newStu,
            [],
            [],
            payload.settings.activeSemester,
            availableMaterials
          )
        ),
        gradesCount: 0,
      });
      createdStudentsRaw.push(newStu);
      student = newStu;
      createdStudentsCount += 1;
    }
    if (!student) return;

    const matInfo = matchMaterialForImport(
      String(row.materialCode || availableMaterials[0]?.code || 'ATLETIK')
    );
    const semester = String(
      row.semester || payload.settings.activeSemester
    ).trim();
    if (semester && !semesters.includes(semester)) {
      semesters.push(semester);
    }

    const praktikScore = parseOptionalScore(row.praktikScore);
    const pengetahuanScore = parseOptionalScore(row.pengetahuanScore);
    const cleanedTeacherNote = String(row.teacherNote ?? '').trim();
    if (
      praktikScore === null &&
      pengetahuanScore === null &&
      cleanedTeacherNote.length === 0
    ) {
      return;
    }

    const existing = workingGrades.find(
      (g) =>
        g.studentId === student!.id &&
        g.semester === semester &&
        g.materialCode === matInfo.code
    );

    const finalPraktik =
      existing && importMode === 'merge' && praktikScore === null
        ? existing.praktikScore
        : praktikScore;
    const finalPengetahuan =
      existing && importMode === 'merge' && pengetahuanScore === null
        ? existing.pengetahuanScore
        : pengetahuanScore;

    const autoImpDesc = buildAutoGradeDescription(
      finalPraktik,
      finalPengetahuan,
      matInfo.name
    );
    const isCustomImportedNote =
      cleanedTeacherNote.length > 0 &&
      !isAutoGeneratedGradeDescription(cleanedTeacherNote);

    let savedGrade: GradeRecord;
    if (existing) {
      existing.materialName = matInfo.name;
      existing.praktikScore = finalPraktik;
      existing.pengetahuanScore = finalPengetahuan;
      if (isCustomImportedNote) {
        existing.teacherNote = cleanedTeacherNote;
      } else if (
        autoImpDesc &&
        (isReplaceableAutoOrPlaceholderNote(existing.teacherNote) ||
          isAutoGeneratedGradeDescription(cleanedTeacherNote) ||
          !cleanedTeacherNote)
      ) {
        existing.teacherNote = autoImpDesc;
      }
      existing.updatedAt = nowIso;
      savedGrade = existing;
      editedCount += 1;
    } else {
      savedGrade = {
        id: `grd-imp-${batchTs}-${idx}`,
        studentId: student.id,
        semester,
        materialCode: matInfo.code as MaterialCode,
        materialName: matInfo.name,
        praktikScore: finalPraktik,
        pengetahuanScore: finalPengetahuan,
        teacherNote:
          (isCustomImportedNote ? cleanedTeacherNote : '') ||
          autoImpDesc ||
          'Silakan minta nilai dengan praktik atau tugas kepada guru PJOK.',
        updatedAt: nowIso,
      };
      workingGrades.push(savedGrade);
      createdCount += 1;
    }
    savedGrades.push(savedGrade);

    const pStr = finalPraktik !== null ? String(finalPraktik) : 'Kosong';
    const kStr =
      finalPengetahuan !== null ? String(finalPengetahuan) : 'Kosong';
    createdNotifications.push({
      id: `notif-imp-${batchTs}-${idx}`,
      studentId: student.id,
      targetRole: 'all',
      type: 'GRADE_UPDATE',
      title: `Pembaruan Nilai ${matInfo.name}`,
      message: `Nilai ${semester} diperbarui melalui import rekap guru: Praktik ${pStr} · Pengetahuan ${kStr}.`,
      isRead: false,
      whatsappSent: false,
      whatsappUrl: buildWhatsappUrl(
        student.parentWhatsapp,
        `[SMPN 2 Ciamis - PJOK] Nilai ${matInfo.name} (${semester}) ananda ${student.name} telah diperbarui: Praktik ${pStr}, Pengetahuan ${kStr}.`
      ),
      createdAt: nowIso,
    });
  });

  const importedIds = new Set(savedGrades.map((g) => g.id));
  const reconciledAfterImport = reconcileAllGradesConsistency({
    students: studentsList,
    materials: availableMaterials,
    grades: workingGrades,
  });
  if (reconciledAfterImport.changed) {
    const oldMap = new Map(workingGrades.map((g) => [g.id, g]));
    workingGrades = reconciledAfterImport.grades;
    workingGrades.forEach((g) => {
      if (importedIds.has(g.id)) return;
      const prev = oldMap.get(g.id);
      if (
        !prev ||
        prev.pengetahuanScore !== g.pengetahuanScore ||
        prev.teacherNote !== g.teacherNote
      ) {
        savedGrades.push(g);
        importedIds.add(g.id);
      }
    });
  }

  const createdStudentsList = recomputeStudentSummaries(
    createdStudentsRaw,
    workingGrades,
    payload.attendance,
    payload.settings.activeSemester,
    availableMaterials
  );

  return {
    ok: true,
    mode: importMode,
    createdCount,
    updatedCount: editedCount + createdCount,
    editedCount,
    removedCount: importMode === 'replace' ? previousCount : 0,
    createdStudents: createdStudentsCount,
    savedGrades: importMode === 'replace' ? workingGrades : savedGrades,
    createdStudentsList,
    createdNotifications,
    availableSemesters: semesters,
  };
}

