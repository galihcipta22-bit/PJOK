export type GradePredicate = 'kurang' | 'cukup' | 'baik' | 'sangat baik';

export function parseScoreInput(
  raw: number | string | null | undefined
): number | null {
  if (raw === null || raw === undefined) return null;
  if (typeof raw === 'number') {
    if (Number.isNaN(raw)) return null;
    return Math.max(0, Math.min(100, raw));
  }
  const trimmed = raw.trim();
  if (trimmed === '') return null;
  const parsed = Number(trimmed);
  if (Number.isNaN(parsed)) return null;
  return Math.max(0, Math.min(100, parsed));
}

export function getScorePredicate(score: number): GradePredicate {
  if (score < 80) return 'kurang';
  if (score <= 85) return 'cukup';
  if (score <= 90) return 'baik';
  return 'sangat baik';
}

export type GradePredicateLetter = 'A' | 'B' | 'C' | 'D';

export function getScorePredicateInfo(score: number): {
  letter: GradePredicateLetter;
  label: string;
} {
  if (score > 90) return { letter: 'A', label: '(A) Sangat Baik' };
  if (score >= 86) return { letter: 'B', label: '(B) Baik' };
  if (score >= 80) return { letter: 'C', label: '(C) Cukup' };
  return { letter: 'D', label: '(D) Kurang' };
}

export function getPraktikDescription(
  score: number | string | null | undefined,
  materialName?: string
): string {
  const num = parseScoreInput(score);
  if (num === null) return '';
  const pred = getScorePredicate(num);
  const matLabel = (materialName || '').trim() || 'materi inti';
  return `${pred} menguasai keterampilan ${matLabel}`;
}

export function getPengetahuanDescription(
  score: number | string | null | undefined
): string {
  const num = parseScoreInput(score);
  if (num === null) return '';
  if (num === 0) {
    return 'Nilai Pengetahuan akan terisi apabila sudah melakukan Ujian STS & SAJ';
  }
  const pred = getScorePredicate(num);
  return `${pred} menguasai pengetahuan dalam semua bidang olahraga`;
}

export function buildAutoGradeDescription(
  praktikScore: number | string | null | undefined,
  pengetahuanScore: number | string | null | undefined,
  materialName?: string
): string {
  const pDesc = getPraktikDescription(praktikScore, materialName);
  const kDesc = getPengetahuanDescription(pengetahuanScore);

  if (pDesc && kDesc) {
    return `Praktik: ${pDesc}. Pengetahuan: ${kDesc}.`;
  }
  if (pDesc) {
    return `Praktik: ${pDesc}.`;
  }
  if (kDesc) {
    return `Pengetahuan: ${kDesc}.`;
  }
  return '';
}

export function isAutoGeneratedGradeDescription(
  note: string | null | undefined
): boolean {
  const trimmed = (note || '').trim();
  if (!trimmed) return false;
  return (
    /^(Praktik:\s*(kurang|cukup|baik|sangat baik)\s+menguasai keterampilan|Pengetahuan:\s*((kurang|cukup|baik|sangat baik)\s+menguasai pengetahuan dalam semua bidang olahraga|Nilai Pengetahuan akan terisi apabila sudah melakukan Ujian STS & SAJ))/i.test(
      trimmed
    ) ||
    trimmed === 'Capaian dievaluasi oleh Galih Cipta Setia, S.Pd.' ||
    trimmed === 'Diimpor dari rekap spreadsheet Excel/CSV.'
  );
}

export function isReplaceableAutoOrPlaceholderNote(
  note: string | null | undefined
): boolean {
  const trimmed = (note || '').trim();
  if (!trimmed) return true;
  if (isAutoGeneratedGradeDescription(trimmed)) return true;
  return (
    trimmed === 'Silakan minta nilai dengan praktik atau tugas.' ||
    trimmed === 'Silakan minta nilai dengan praktik atau tugas kepada guru PJOK.'
  );
}

export function resolveUnifiedPengetahuanScore(
  semesterGrades: ReadonlyArray<{
    pengetahuanScore?: number | null;
    updatedAt?: string;
  }>
): number | null {
  const withScore = semesterGrades.filter(
    (g): g is { pengetahuanScore: number; updatedAt?: string } =>
      typeof g.pengetahuanScore === 'number' &&
      Number.isFinite(g.pengetahuanScore)
  );
  if (withScore.length === 0) return null;
  const unique = new Set(withScore.map((g) => g.pengetahuanScore));
  if (unique.size === 1) {
    return withScore[0].pengetahuanScore;
  }
  let latest = withScore[0];
  let latestTs = latest.updatedAt ? Date.parse(latest.updatedAt) || 0 : 0;
  for (let i = 1; i < withScore.length; i++) {
    const g = withScore[i];
    const ts = g.updatedAt ? Date.parse(g.updatedAt) || 0 : 0;
    if (ts >= latestTs) {
      latest = g;
      latestTs = ts;
    }
  }
  return latest.pengetahuanScore;
}
